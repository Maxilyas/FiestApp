test('sonde : arrivé au podium', () => {
  h = horloge()
  const s = salle([{ id: 'q', title: 'Q', questions: [qcm('Un ?'), qcm('Deux ?')] }])
  s.inscrire('Zoé')
  s.inscrire('Yves')
  s.inscrire('Xavier')
  s.lancer()
  s.choisir('q')
  h.avancer(3000)
  s.repondre('Zoé', { type: 'answer', choice: 0 })
  s.repondre('Yves', { type: 'answer', choice: 1 })
  s.repondre('Xavier', { type: 'answer', choice: 1 })
  h.avancer(700)
  s.commande({ type: 'next', ...s.visee() })
  s.repondre('Zoé', { type: 'answer', choice: 0 })
  s.repondre('Yves', { type: 'answer', choice: 1 })
  s.repondre('Xavier', { type: 'answer', choice: 1 })
  h.avancer(700)
  s.commande({ type: 'next', ...s.visee() })
  console.log('phase', s.st.phase)
  console.log('podium avant', s.vueHote()?.standings?.map((r: any) => `${r.name}:${r.points}:${r.rank}`))
  s.rejoindre('Aaron')
  console.log('podium après', s.vueHote()?.standings?.map((r: any) => `${r.name}:${r.points}:${r.rank}`))
  console.log('téléphone d’Aaron', JSON.stringify({ podium: s.vueDe('Aaron')?.podium?.map((r: any) => r.name), idx: s.vueDe('Aaron')?.yourPodiumIndex, rank: s.vueDe('Aaron')?.yourQuizRank }))
  console.log('téléphone de Xavier', JSON.stringify({ podium: s.vueDe('Xavier')?.podium?.map((r: any) => r.name), idx: s.vueDe('Xavier')?.yourPodiumIndex }))
  s.fermer()
})

