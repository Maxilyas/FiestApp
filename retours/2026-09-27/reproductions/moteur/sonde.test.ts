test('sonde : « au clic » pendant l’intertitre', () => {
  h = horloge()
  const s = salle([{ id: 'q', title: 'Q', questions: [qcm('Un ?'), qcm('Deux ?', { intertitre: 'Manche 2' })] }])
  s.inscrire('Alice')
  s.lancer({ autoNextSeconds: 10 })
  s.choisir('q')
  h.avancer(3000)
  s.repondre('Alice', { type: 'answer', choice: 0 })
  h.avancer(700)
  console.log('révélée', s.st.phase, s.chronos())
  h.avancer(10000)
  console.log('intertitre', s.st.phase, s.chronos(), 'vue hôte deadline', s.vueHote()?.deadline, 'auto', s.vueHote()?.autoNextSeconds)
  s.commande({ type: 'autoNext', seconds: null })
  console.log('au clic', s.st.phase, s.chronos(), 'vue hôte deadline', s.vueHote()?.deadline, 'auto', s.vueHote()?.autoNextSeconds)
  h.avancer(10000)
  console.log('10 s plus tard', s.st.phase)
  s.fermer()
})

