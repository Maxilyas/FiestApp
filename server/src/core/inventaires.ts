/** L'inventaire d'un sous-thème de sa catégorie, s'il en a un. */
export const inventaireDe = (categorie: string, sousTheme: string): Inventaire | undefined =>
  INVENTAIRES.find(i => i.categorie === categorie && i.sousTheme === sousTheme)

/** Les inventaires d'un thème : ceux de ses sous-thèmes, dans l'ordre du catalogue. */
export function inventairesDuTheme(theme: Pick<Sujet, 'sousThemes'>): Inventaire[] {
  return INVENTAIRES.filter(i => !!theme.sousThemes?.[i.categorie]?.includes(i.sousTheme))
}

/**
 * `total` questions réparties entre les familles de ces inventaires, à
 * proportion de leurs poids — les plus forts restes d'abord, pour tomber
 * juste : la commande d'une génération (`generer-campagne.ts preparer
 * --inventaire`) et l'inventaire qu'on relit (`base-campagne.ts inventaire`)
 * disent les mêmes nombres.
 */
export function repartirLesFamilles(inventaires: readonly Inventaire[], total: number): { inventaire: Inventaire; famille: FamilleDInventaire; n: number }[] {
  const familles = inventaires.flatMap(inventaire => inventaire.familles.map(famille => ({ inventaire, famille })))
  const poids = familles.reduce((s, f) => s + f.famille.poids, 0)
  if (poids <= 0 || total <= 0) return familles.map(f => ({ ...f, n: 0 }))
  const parts = familles.map(f => (total * f.famille.poids) / poids)
  const n = parts.map(p => Math.floor(p))
  const restes = parts.map((p, i) => ({ i, reste: p - Math.floor(p) })).sort((a, b) => b.reste - a.reste || a.i - b.i)
  for (let manque = total - n.reduce((s, x) => s + x, 0), k = 0; manque > 0; manque--, k++) n[restes[k % restes.length].i]++
  return familles.map((f, i) => ({ ...f, n: n[i] }))
}

/** Sans accents, sans casse, la ponctuation en espaces : « Kiné » et « kine » se retrouvent, « d'œil » et « d oeil » aussi. */
const normaliser = (texte: string) =>
  sansAccent(texte)
    .replace(/œ/g, 'oe')
    .replace(/æ/g, 'ae')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()

/** Un sujet de l'inventaire : le nom qu'on lit, et les racines qui le retrouvent dans une question. */
export function lireLeSujet(sujet: string): { nom: string; racines: string[] } {
  const [nom, ...racines] = sujet.split('|')
  return { nom, racines: (racines.length > 0 ? racines : [nom]).map(normaliser).filter(Boolean) }
}

/** Une racine retrouvée : au début d'un mot ; le mot entier pour quatre lettres au plus, un sigle — « orl » n'est pas Orléans. */
function retrouvee(texte: string, racine: string): boolean {
  return racine.length <= 4 ? texte.includes(` ${racine} `) : texte.includes(` ${racine}`)
}

/** Ce qu'une question montre de son sujet : l'intitulé, la bonne réponse, ses entités — jamais les leurres, qui en nomment d'autres. */
export interface QuestionCouverte {
  texte: string
  reponses: readonly string[]
  bonne: number
  meta: Pick<MetadonneesDeQuestion, 'entites'>
}

export interface CouvertureDUneFamille {
  famille: string
  sujets: { nom: string; questions: number }[]
}

/**
 * Combien de questions abordent chaque sujet de l'inventaire. Une mesure de
 * mots, pas de sens : elle compte large — une racine peut se croiser par
 * hasard —, et sert à voir ce qui reste à zéro, pas à départager deux sujets.
 */
export function couverture(inventaire: Inventaire, questions: readonly QuestionCouverte[]): CouvertureDUneFamille[] {
  const textes = questions.map(q => ` ${normaliser([q.texte, q.reponses[q.bonne] ?? '', ...q.meta.entites.map(e => e.nom)].join(' '))} `)
  return inventaire.familles.map(f => ({
    famille: f.nom,
    sujets: f.sujets.map(s => {
      const { nom, racines } = lireLeSujet(s)
      return { nom, questions: textes.filter(t => racines.some(r => retrouvee(t, r))).length }
    }),
  }))
}
