// Les inventaires des sous-thèmes : tout ce qu'un sous-thème doit couvrir,
// famille par famille. Le propriétaire voulait « couvrir tous les métiers de
// la médecine et du paramédical, et toutes les danses, qu'il faudra
// regrouper » (le 15 octobre 2026) : un sous-thème seul laisse le rédacteur
// aux faits qu'il connaît le mieux — vingt tangos, pas une kizomba, dix
// cardiologues et pas un orthoptiste. Un sous-thème par famille aurait pris
// à chaque catégorie une part de ses séries, de ses sentiers et de ses
// défis : six sous-thèmes de danse, et toute série de musique était à moitié
// dansée. Les familles vivent donc ici, à côté du catalogue, sans rien
// changer à la base ni au tirage.
//
// L'inventaire se donne avec la part de son sous-thème (`partDeLaCategorie`),
// la routine du matin comprise ; une génération en nombre le commande
// famille par famille (`generer-campagne.ts preparer --inventaire`), deux
// familles s'écrivant en même temps sans poser les mêmes faits ; et
// `base-campagne.ts couverture` dit les sujets qu'aucune question n'aborde
// encore. Le mot « programme » était pris : c'est celui d'une soirée.

export interface FamilleDInventaire {
  /** Son nom, court : il se lit dans la consigne, dans le plan d'une génération et dans la couverture. */
  nom: string
  /** Sa part d'une commande en nombre : un poids, que la commande suit à proportion. */
  poids: number
  /**
   * Ce qu'elle couvre : chaque sujet mérite au moins sa question, les plus
   * grands plusieurs. « Nom|racine|racine » : les racines retrouvent le sujet
   * dans une question (`couverture`) — au début d'un mot, ou le mot entier
   * pour une racine de quatre lettres au plus (« orl » n'est pas Orléans) ;
   * sans racine, son nom.
   */
  sujets: readonly string[]
}

export interface Inventaire {
  categorie: Categorie
  sousTheme: string
  /** Ce que le sous-thème prend, et ce qu'il laisse à ses voisins : quelques phrases pour le rédacteur. */
  perimetre: string
  /** Ce qu'il ne faut pas demander : ce qui a bougé ces dernières années, ce qui ne se vérifie pas. */
  prudence?: string
  familles: readonly FamilleDInventaire[]
}

